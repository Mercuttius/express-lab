import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
const base=process.env.TEST_URL??'http://127.0.0.1:5173';
if(!['localhost','127.0.0.1'].includes(new URL(base).hostname))throw Error('Este teste só pode gravar no ambiente local.');
const auth=await fetch(base+'/signin-with-chatgpt?return_to=/',{redirect:'manual'});
const cookie=auth.headers.getSetCookie().map(c=>c.split(';')[0]).join('; ');
assert.ok(cookie,'Login local retornou cookie');
const sessions=[];mkdirSync('work',{recursive:true});
async function api(path,body,expected=200,options={}){const r=await fetch(base+'/api/'+path,{method:body?'POST':'GET',headers:{Cookie:cookie,Origin:base,...(body?{'Content-Type':'application/json'}:{}),...options.headers},body:body?JSON.stringify(body):undefined});const raw=await r.text();let d;try{d=JSON.parse(raw)}catch{d={error:raw}}assert.equal(r.status,expected,JSON.stringify(d));return d;}
async function begin(exerciseId){const s=await api('practice',{exerciseId},201);sessions.push(s.id);writeFileSync('work/test-sessions.json',JSON.stringify(sessions));return s.id;}
const baseline=await api('progress');
const id='routes-easy-01';const before=baseline.counts[id]??{correct:0,wrong:0,assisted:0};
await api('practice',{exerciseId:'inexistente'},400);
await api('practice',{exerciseId:id},403,{headers:{Origin:'https://fora.example'}});
const s=await begin(id);
await api('attempts',{sessionId:s,requestId:crypto.randomUUID(),answers:['']},400);
const wrong={sessionId:s,requestId:crypto.randomUUID(),answers:['post']};
assert.equal((await api('attempts',wrong)).correct,false);
assert.equal((await api('attempts',wrong)).correct,false);
assert.equal((await api('progress')).counts[id].wrong,before.wrong+1,'Retry não duplica erro');
const correct={sessionId:s,requestId:crypto.randomUUID(),answers:[' get ']};
assert.equal((await api('attempts',correct)).correct,true);
assert.equal((await api('attempts',correct)).correct,true);
await api('attempts',{...correct,requestId:crypto.randomUUID()},409);
let progress=await api('progress');assert.equal(progress.counts[id].correct,before.correct+1);
const score=progress.totals.score;
const s2=await begin(id);assert.deepEqual((await api('solution',{sessionId:s2})).answers,['get']);
const assisted=await api('attempts',{sessionId:s2,requestId:crypto.randomUUID(),answers:['get']});assert.equal(assisted.assisted,true);
progress=await api('progress');assert.equal(progress.totals.score,score,'Consulta não aumenta proficiência');
assert.equal(progress.counts[id].correct,before.correct+2);assert.equal(progress.counts[id].assisted,before.assisted+1);
assert.ok(progress.repeated.some(r=>r.id===id&&r.times===before.correct+2));
assert.equal(progress.today.completed,baseline.today.completed+(before.correct?0:1),'Repetir não duplica exercícios únicos no dia');
const s3=await begin('database-easy-01');assert.equal((await api('attempts',{sessionId:s3,requestId:crypto.randomUUID(),answers:['select']})).correct,true,'SQL aceita caixa diferente');
const s4=await begin(id);assert.equal((await api('attempts',{sessionId:s4,requestId:crypto.randomUUID(),answers:['g e t']})).correct,false,'Espaços não juntam identificadores diferentes');
const concurrent=await begin('routes-easy-02');
const results=await Promise.all([1,2].map(async()=>{const r=await fetch(base+'/api/attempts',{method:'POST',headers:{Cookie:cookie,Origin:base,'Content-Type':'application/json'},body:JSON.stringify({sessionId:concurrent,requestId:crypto.randomUUID(),answers:['post']})});return r.status;}));
assert.deepEqual(results.sort(),[200,409],'Acertos concorrentes só fecham a sessão uma vez');
const anon=await fetch(base+'/api/progress');assert.equal(anon.status,401);
console.log('PASS: erro, acerto, repetição, assistência, persistência, idempotência, concorrência, validação, origem e login.');
